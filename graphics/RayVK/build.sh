#!/bin/sh
# build.sh -- builds librcvk.so for RayVK.bas
# Needs: gcc and libvulkan-dev (sudo apt install libvulkan-dev)
# Optional: glslang-tools, to rebuild the shader after editing rcvk.comp
set -e
cd "$(dirname "$0")"

if command -v glslangValidator >/dev/null 2>&1; then
    echo "Compiling rcvk.comp -> SPIR-V"
    glslangValidator -V rcvk.comp -o rcvk.spv
    # turn rcvk.spv into the C header rcvk_spv.h
    {
        echo "/* rcvk_spv.h -- SPIR-V for rcvk.comp, generated by build.sh. Do not edit. */"
        echo "static const unsigned int rcvk_spv[] = {"
        od -An -v -tx4 -w32 rcvk.spv | sed 's/ \([0-9a-f]\{8\}\)/ 0x\1,/g'
        echo "};"
        echo "static const unsigned int rcvk_spv_size = sizeof(rcvk_spv);"
    } > rcvk_spv.h
else
    echo "glslangValidator not found - using the existing rcvk_spv.h"
fi

echo "Building librcvk.so"
gcc -O2 -Wall -shared -fPIC rcvk.c -o librcvk.so -l:libvulkan.so.1 -lm
echo "Done: librcvk.so"
