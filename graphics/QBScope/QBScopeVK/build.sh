#!/bin/sh
# build.sh -- builds libscopevk.so for QBScopeVK
#
# Needs:  sudo apt install libvulkan-dev
# Optional (only if you edit scopevk.comp):  sudo apt install glslang-tools
# Without glslangValidator the shipped scopevk_spv.h is used as-is.
set -e
cd "$(dirname "$0")"

if command -v glslangValidator >/dev/null 2>&1; then
    echo "Compiling scopevk.comp -> SPIR-V"
    glslangValidator -V scopevk.comp -o scopevk.spv
    {
        echo "/* scopevk_spv.h -- SPIR-V of scopevk.comp, generated by build.sh. Do not edit. */"
        echo "static const unsigned int scopevk_spv[] = {"
        od -An -v -tx4 -w32 scopevk.spv | sed 's/ \([0-9a-f]\{8\}\)/ 0x\1,/g'
        echo "};"
        echo "static const unsigned int scopevk_spv_size = sizeof(scopevk_spv);"
    } > scopevk_spv.h
else
    echo "glslangValidator not found - using the existing scopevk_spv.h"
fi

echo "Building libscopevk.so"
gcc -O2 -Wall -shared -fPIC scopevk.c -o libscopevk.so -l:libvulkan.so.1 -lm
echo "Done: libscopevk.so"
